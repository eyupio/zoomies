// `zoomies mcp` is the fleet offered to a coding agent over the Model Context
// Protocol. It is deliberately one more API client and nothing else: it speaks
// MCP on its own standard input and output to the agent that launched it, and
// calls the controller's REST API with a token, exactly as the rest of the CLI
// does. So it adds no authority -- what an agent can see or do is what the
// token's role already allows, and the controller cannot tell it apart from
// `zoomies jobs list`.
//
// The protocol and the tools live in internal/mcp, which the controller's own
// /mcp endpoint serves as well; this is the stdio transport, for an agent that
// would rather launch a process than reach the controller over HTTP.

// runMCP is `zoomies mcp`.
func runMCP(ctx context.Context, e *env, args []string) error {
	fs := newFlagSet(e, "zoomies mcp [--allow-actions] [--describe [--output json|markdown]]",
		"Serve this fleet to a coding agent over the Model Context Protocol, on standard\n"+
			"input and output. The agent's MCP configuration launches this command; it is\n"+
			"not something to run by hand.\n\n"+
			"It reads through the REST API with the same URL and token as the rest of the\n"+
			"CLI, so a viewer token is enough and is what to give it. Without --allow-actions\n"+
			"it offers read-only tools and nothing else.\n\n"+
			"With --describe it serves nothing: it prints every tool, resource and prompt\n"+
			"the server has, action tools included and marked, and exits. No controller is\n"+
			"needed; skills/zoomies/mcp-reference.md is generated from it.")
	cf := registerClientFlags(fs, false)
	allowAdmin := fs.Bool("allow-admin", false, "with --allow-actions, also offer edit_host, clear_host_throttle, get_settings and update_settings; the token must be an administrator's")
	allowActions := fs.Bool("allow-actions", false, "also offer rerun_job, drain_runner, update_pool, update_host, apply_remedy and context_publish; the token's role must permit them too")
	describe := fs.Bool("describe", false, "print the tools, resources and prompts this server has and exit, without serving")
	output := fs.String("output", "markdown", "with --describe: json or markdown")
	fs.example(
		"zoomies mcp --url https://zoomies.example.com",
		"claude mcp add zoomies -e ZOOMIES_URL=https://zoomies.example.com -e ZOOMIES_TOKEN=zoo_... -- zoomies mcp",
	)
	if err := fs.parse(args); err != nil {
		return err
	}
	if err := fs.noMoreArgs(); err != nil {
		return err
	}
	if *describe {
		switch *output {
		case "json":
			enc := json.NewEncoder(e.out)
			enc.SetIndent("", "  ")
			return enc.Encode(mcp.Describe())
		case "markdown":
			_, err := e.out.Write([]byte(renderMCPReference(mcp.Describe())))
			return err
		default:
			return usagef("mcp", "--output must be json or markdown, not %q", *output)
		}
	}
	client, err := cf.client()
	if err != nil {
		return err
	}
	return mcp.New(mcpAPI{client}, mcp.Options{
		Offer: func(tool string) bool { return *allowActions && (!mcp.IsAdminTool(tool) || *allowAdmin) },
		Refusal: func(tool string) string {
			if mcp.IsAdminTool(tool) && *allowActions {
				return tool + " is an administrator tool: restart this server with `zoomies mcp --allow-actions --allow-admin` and an administrator's token"
			}
			return tool + " changes the fleet, and this server was started read-only; restart it with `zoomies mcp --allow-actions` and a token whose role permits it"
		},
	}).ServeStdio(ctx, e.in, e.out)
}

// mcpAPI is the CLI's client as the MCP tools see it: the same URL, token and
// timeout every other command uses, and the same refusals.
type mcpAPI struct{ c *apiClient }

func (a mcpAPI) Call(ctx context.Context, method, path string, q url.Values) ([]byte, error) {
	return a.c.do(ctx, method, path, q, nil, nil)
}

func (a mcpAPI) CallBody(ctx context.Context, method, path string, q url.Values, body []byte) ([]byte, error) {
	return a.c.do(ctx, method, path, q, json.RawMessage(body), nil)
}

func (a mcpAPI) Stream(ctx context.Context, path, accept string) (io.ReadCloser, error) {
	resp, err := a.c.stream(ctx, path, nil, accept)
	if err != nil {
		return nil, err
	}
	return resp.Body, nil
}

// renderMCPReference is the Markdown the skill carries for the MCP surface:
// the read-only tools, then the ones that change the fleet with what unlocks
// them, then the resources and the prompts, each tool's arguments flattened
// from its schema so an agent can read them without parsing JSON.
func renderMCPReference(ref mcp.Reference) string {
	var b strings.Builder
	b.WriteString("# zoomies MCP reference\n\n")
	fmt.Fprintf(&b, "Generated by `zoomies mcp --describe` from %s. Do not edit: `make generate` rewrites it, and a test fails when it differs from the binary. "+
		"These are the tools, resources and prompts the Zoomies MCP server offers, over `zoomies mcp` on standard input and output or at the controller's `/mcp` endpoint. "+
		"Every tool calls the controller's REST API as the token it was given, so none can see or do what that token's role could not.\n", version.Short())
	writeTool := func(t mcp.ToolReference) {
		fmt.Fprintf(&b, "\n### %s\n\n%s\n\n%s\n", t.Name, t.Title, t.Description)
		props := mcp.SchemaProperties(t.InputSchema)
		if len(props) == 0 {
			b.WriteString("\nNo arguments.\n")
			return
		}
		b.WriteString("\nArguments:\n\n")
		for _, p := range props {
			kind := p.Type
			if p.Required {
				kind += ", required"
			}
			fmt.Fprintf(&b, "* `%s` (%s): %s", p.Name, kind, p.Description)
			if len(p.Enum) > 0 {
				fmt.Fprintf(&b, " One of `%s`.", strings.Join(p.Enum, "`, `"))
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("\n## Read-only tools\n\nOffered always. None changes anything.\n")
	for _, t := range ref.Tools {
		if !t.Action {
			writeTool(t)
		}
	}
	b.WriteString("\n## Tools that change the fleet\n\nOffered only when the server is started with `zoomies mcp --allow-actions`, and the token's role must permit each one too. The administrator tools need `--allow-admin` as well and an administrator's token. Without that leave, a call to one is answered with a sentence saying how to start the server so it is offered.\n")
	for _, t := range ref.Tools {
		if t.Action {
			writeTool(t)
			if t.Admin {
				b.WriteString("\nAn administrator tool: needs `--allow-admin`.\n")
			}
		}
	}
	b.WriteString("\n## Resources\n\nWhat an agent loads to learn the vocabulary before it works, without spending a tool call.\n")
	for _, r := range ref.Resources {
		kind := "Resource"
		if r.Template {
			kind = "Resource template"
		}
		fmt.Fprintf(&b, "\n### `%s`\n\n%s: %s. %s\n", r.URI, kind, r.Title, r.Description)
	}
	b.WriteString("\n## Prompts\n\nThe common questions with the way to work written in: which tools to call, in what order, and what the answer owes the person.\n")
	for _, p := range ref.Prompts {
		fmt.Fprintf(&b, "\n### %s\n\n%s\n\n%s\n", p.Name, p.Title, p.Description)
		if len(p.Arguments) == 0 {
			b.WriteString("\nNo arguments.\n")
			continue
		}
		b.WriteString("\nArguments:\n\n")
		for _, a := range p.Arguments {
			kind := "string"
			if a.Required {
				kind += ", required"
			}
			fmt.Fprintf(&b, "* `%s` (%s): %s\n", a.Name, kind, a.Description)
		}
	}
	return b.String()
}
